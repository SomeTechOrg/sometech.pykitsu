# --------------------------------------------------------------------------- helpers


def snake(text: str) -> str:
    text = re.sub(r"[^0-9a-zA-Z]+", "_", text)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = re.sub(r"_+", "_", text).strip("_").lower()
    if not text:
        text = "value"
    if text[0].isdigit():
        text = "n" + text
    return text


GROUP_RENAMES = {"import": "imports"}


def group_name(tag: str) -> str:
    """Module / property name of a tag (always a valid identifier)."""
    name = snake(tag)
    name = GROUP_RENAMES.get(name, name)
    return name + "_" if keyword.iskeyword(name) else name


def pascal(text: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in snake(text).split("_"))


def safe_ident(name: str, taken: set[str] | None = None) -> str:
    ident = snake(name) if not name.isidentifier() else name
    if keyword.iskeyword(ident) or ident in ("self", "cls"):
        ident += "_"
    if taken is not None:
        base = ident
        i = 2
        while ident in taken:
            ident = f"{base}_{i}"
            i += 1
        taken.add(ident)
    return ident


def field_ident(name: str) -> str:
    ident = name if name.isidentifier() else snake(name)
    if (
        keyword.iskeyword(ident)
        or ident in RESERVED_MODEL_ATTRS
        or ident.startswith("_")
        or ident.startswith("model_")
    ):
        ident = ident.lstrip("_") + "_"
        if ident.startswith("model_"):
            ident = "f_" + ident
    return ident


def _split_top(expr: str, sep: str) -> list[str]:
    """Split ``expr`` on ``sep`` outside brackets and string literals."""
    parts: list[str] = []
    depth, quote, start, i = 0, "", 0, 0
    while i < len(expr):
        ch = expr[i]
        if quote:
            if ch == "\\":
                i += 1
            elif ch == quote:
                quote = ""
        elif ch in "'\"":
            quote = ch
        elif ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        elif depth == 0 and expr.startswith(sep, i):
            parts.append(expr[start:i].strip())
            start = i + len(sep)
            i = start
            continue
        i += 1
    parts.append(expr[start:].strip())
    return parts


def py39_type(expr: str) -> str:
    """Rewrite ``A | B | None`` unions as ``Optional[Union[A, B]]`` (Python 3.9 safe).

    Pydantic evaluates model annotations at runtime, and ``X | Y`` on classes
    only works from Python 3.10.
    """
    parts = _split_top(expr, "|")
    if len(parts) == 1:
        head, bracket, rest = expr.partition("[")
        if not bracket or head == "Literal":
            return expr
        inner = rest[:-1]  # drop the closing bracket
        return f"{head}[{', '.join(py39_type(a) for a in _split_top(inner, ','))}]"
    optional = "None" in parts
    members = [py39_type(x) for x in parts if x != "None"]
    core = members[0] if len(members) == 1 else f"Union[{', '.join(members)}]"
    return f"Optional[{core}]" if optional else core


def py39_param(param: str) -> str:
    """Convert the annotation of a ``name: type = default`` signature entry."""
    name, colon, rest = param.partition(": ")
    if not colon:
        return param
    annotation, eq, default = rest.partition(" = ")
    return f"{name}: {py39_type(annotation)}{eq}{default}"


def doc_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()


def wrap(text: str, indent: str, width: int = 88) -> list[str]:
    import textwrap

    out: list[str] = []
    for para in doc_escape(text).splitlines():
        if not para.strip():
            out.append("")
            continue
        out.extend(
            textwrap.wrap(
                para.strip(),
                width=width - len(indent),
                break_long_words=False,
                break_on_hyphens=False,
            )
            or [""]
        )
    return [indent + line if line else "" for line in out]


def schema_key(schema: Any) -> str:
    """Structural hash of a schema, ignoring documentation-only keys."""

    def strip(s: Any) -> Any:
        if isinstance(s, dict):
            return {
                k: strip(v)
                for k, v in sorted(s.items())
                if k not in ("description", "example", "examples", "title")
            }
        if isinstance(s, list):
            return [strip(v) for v in s]
        return s

    return hashlib.sha1(json.dumps(strip(schema), sort_keys=True).encode()).hexdigest()


# --------------------------------------------------------------------------- model registry


@dataclass
class ModelField:
    name: str  # python identifier
    alias: str  # json key
    type: str
    required: bool
    description: str


@dataclass
class ModelDef:
    name: str
    fields: list[ModelField]
    description: str = ""
    extra: str = "allow"


class TypeContext:
    """Resolves schemas to python type expressions, collecting models on the way."""

    def __init__(self, components: dict[str, Any], core_names: set[str], module: str) -> None:
        self.components = components
        self.core_names = core_names
        self.module = module  # "core" or tag module
        self.models: dict[str, ModelDef] = {}
        self.aliases: dict[str, str] = {}
        self.by_key: dict[str, str] = {}
        self.used_core: set[str] = set()
        self.typing: set[str] = set()  # names from typing / datetime used
        self.needs_file_input = False

    # -- naming
    def unique_model_name(self, name: str) -> str:
        base = name
        i = 2
        while name in self.models or name in self.aliases or name in self.core_names:
            name = f"{base}{i}"
            i += 1
        return name

    # -- schema → python type
    def py_type(self, s: dict[str, Any] | None, hint: str, *, for_input: bool = False) -> str:
        if not s:
            self.typing.add("Any")
            return "Any"
        if "$ref" in s:
            ref = s["$ref"].rsplit("/", 1)[-1]
            self.used_core.add(ref)
            return ref
        nullable = s.get("nullable", False)
        t = self._py_type(s, hint, for_input=for_input)
        if nullable and t != "Any" and not t.endswith("| None"):
            t = f"{t} | None"
        return t

    def _py_type(self, s: dict[str, Any], hint: str, *, for_input: bool) -> str:
        for key in ("oneOf", "anyOf"):
            if key in s:
                parts: list[str] = []
                for i, sub in enumerate(s[key]):
                    t = self.py_type(sub, f"{hint}{'Variant' + str(i + 1) if i else ''}", for_input=for_input)
                    for piece in t.split(" | "):
                        if piece not in parts:
                            parts.append(piece)
                if "Any" in parts:
                    self.typing.add("Any")
                    return "Any"
                return " | ".join(parts)
        if "allOf" in s:
            merged: dict[str, Any] = {"type": "object", "properties": {}, "required": []}
            for sub in s["allOf"]:
                if "$ref" in sub:
                    sub = self.components[sub["$ref"].rsplit("/", 1)[-1]]
                merged["properties"].update(sub.get("properties", {}))
                merged["required"] += sub.get("required", [])
            return self._py_type(merged, hint, for_input=for_input)

        typ = s.get("type")
        fmt = s.get("format")
        if "enum" in s and for_input and typ in ("string", "integer", None):
            self.typing.add("Literal")
            return "Literal[" + ", ".join(repr(v) for v in s["enum"] if v is not None) + "]"
        if typ == "string":
            if fmt == "date-time":
                return "_dt.datetime"
            if fmt == "date":
                return "_dt.date"
            if fmt == "binary":
                if for_input:
                    self.needs_file_input = True
                    return "FileInput"
                return "bytes"
            if fmt == "json":
                self.typing.add("Any")
                return "Any"
            return "str"
        if typ == "integer":
            return "int"
        if typ == "number":
            return "float"
        if typ == "boolean":
            return "bool"
        if typ == "array":
            item = self.py_type(s.get("items"), f"{hint}Item", for_input=for_input)
            return f"list[{item}]"
        if typ == "object" or "properties" in s or "additionalProperties" in s:
            props = s.get("properties")
            if props:
                return self.inline_model(s, hint, for_input=for_input)
            ap = s.get("additionalProperties")
            self.typing.add("Any")
            if isinstance(ap, dict) and ap:
                return f"dict[str, {self.py_type(ap, f'{hint}Value', for_input=for_input)}]"
            return "dict[str, Any]"
        self.typing.add("Any")
        return "Any"

    def inline_model(self, s: dict[str, Any], hint: str, *, for_input: bool) -> str:
        key = schema_key(s) + ("i" if for_input else "o")
        if for_input:
            self.typing.add("Any")
        if key in self.by_key:
            # Same shape as an earlier model: give it a readable alias name.
            existing = self.by_key[key]
            name = self.unique_model_name(pascal(hint))
            self.aliases[name] = existing
            return f"{name} | dict[str, Any]" if for_input else name
        name = self.unique_model_name(pascal(hint))
        ref = f"{name} | dict[str, Any]" if for_input else name
        self.by_key[key] = name
        # Reserve the name before recursing (self-referencing / nested names).
        self.models[name] = ModelDef(name=name, fields=[])
        self.models[name] = self.build_model(name, s, for_input=for_input)
        return ref

    def build_model(
        self,
        name: str,
        s: dict[str, Any],
        *,
        for_input: bool,
        extra_props: dict[str, Any] | None = None,
    ) -> ModelDef:
        props = dict(extra_props or {})
        props.update(s.get("properties", {}))
        required = set(s.get("required", [])) if for_input else set()
        fields: list[ModelField] = []
        taken: set[str] = set()
        for json_name, ps in props.items():
            ident = field_ident(json_name)
            if (
                ident in SHADOWING_NAMES
                or ident in self.models
                or ident in self.aliases
                or ident in self.core_names
            ):
                ident += "_"
            while ident in taken:
                ident += "_"
            taken.add(ident)
            ftype = self.py_type(ps, f"{name}{pascal(json_name)}", for_input=for_input)
            fields.append(
                ModelField(
                    name=ident,
                    alias=json_name,
                    type=ftype,
                    required=json_name in required,
                    description=(ps.get("description") or "").strip(),
                )
            )
        return ModelDef(
            name=name,
            fields=fields,
            description=(s.get("description") or "").strip(),
            extra="allow",
        )


def render_models(models: list[ModelDef], *, base: str = "KitsuModel") -> list[str]:
    out: list[str] = []
    for m in models:
        out.append("")
        out.append("")
        out.append(f"class {m.name}({base}):")
        if m.description:
            out.append('    """')
            out.extend(wrap(m.description, "    "))
            out.append('    """')
            out.append("")
        if not m.fields:
            out.append("    pass")
            continue
        for f in m.fields:
            if f.name != f.alias:
                default = f"Field(alias={f.alias!r})" if f.required else f"Field(None, alias={f.alias!r})"
            else:
                default = "" if f.required else "None"
            ftype = (
                f.type
                if f.required
                else (f.type if f.type in ("Any",) or f.type.endswith("| None") else f"{f.type} | None")
            )
            line = f"    {f.name}: {py39_type(ftype)}"
            if default:
                line += f" = {default}"
            out.append(line)
            if f.description:
                desc = f.description.replace("\n", " ")
                out.append(f'    """{doc_escape(desc)}"""')
    return out


# --------------------------------------------------------------------------- operations


@dataclass
class Param:
    py: str  # python identifier
    wire: str  # name on the wire
    type: str
    required: bool
    description: str
    location: str  # path | query | body | file | rawbody


@dataclass
class Operation:
    method: str
    path: str
    tag: str
    summary: str
    description: str
    op: dict[str, Any]
    name: str = ""
    params: list[Param] = field(default_factory=list)
    return_type: str = "None"
    response_kind: str = "json"  # json | binary | none | raw
    body_mode: str = "none"  # none | json | json_props | multipart | json_or_multipart | form
    body_required: bool = False


def method_name_from_summary(summary: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", summary)
    words = [w.lower() for w in words if w.lower() not in ARTICLES]
    return snake("_".join(words)) or "call"


def disambiguate(ops: list[Operation]) -> None:
    groups: dict[str, list[Operation]] = defaultdict(list)
    for op in ops:
        groups[op.name].append(op)
    for name, same in groups.items():
        if len(same) < 2:
            continue
        # Use the path segments that differ to make names unique.
        seg_lists = [[s for s in op.path.strip("/").split("/") if not s.startswith("{")] for op in same]
        common = set.intersection(*(set(s) for s in seg_lists))
        for op, segs in zip(same, seg_lists, strict=True):
            extra = [s for s in segs if s not in common]
            if extra:
                op.name = f"{name}_{snake('_'.join(extra[-2:]))}"
        # Fall back on the http method, then on a counter.
        again: dict[str, list[Operation]] = defaultdict(list)
        for op in same:
            again[op.name].append(op)
        for n2, same2 in again.items():
            if len(same2) > 1:
                for i, op in enumerate(same2):
                    op.name = (
                        f"{n2}_{op.method}"
                        if len({o.method for o in same2}) == len(same2)
                        else f"{n2}_{i + 1}"
                    )


def pick_success(op: dict[str, Any]) -> tuple[str | None, dict[str, Any] | None]:
    responses = op.get("responses", {})
    for code in ("200", "201", "202", "204", "206"):
        if code in responses:
            return code, responses[code]
    for code, r in responses.items():
        if code.startswith("2"):
            return code, r
    return None, None


def component_for(schema: dict[str, Any], summary: str, comp_props: dict[str, set[str]]) -> str | None:
    """Map an inline response object to a component model when unambiguous."""
    props = set(schema.get("properties", {}))
    if len(props - set(BASE_FIELDS)) < 2:
        return None
    cands = [name for name, cp in comp_props.items() if props <= cp]
    if not cands:
        return None
    text = " " + " ".join(re.findall(r"[a-z0-9]+", summary.lower())) + " "
    named = [
        c
        for c in cands
        if f" {snake(c).replace('_', ' ')} " in text or f" {snake(c).replace('_', ' ')}s " in text
    ]
    if len(named) == 1:
        return named[0]
    return None


# --------------------------------------------------------------------------- main generator


class Generator:
    def __init__(self, spec: dict[str, Any], overrides: dict[str, Any]) -> None:
        self.spec = spec
        self.overrides = overrides
        self.components: dict[str, Any] = spec.get("components", {}).get("schemas", {})
        self.comp_props = {
            name: set(s.get("properties", {})) | set(BASE_FIELDS) for name, s in self.components.items()
        }

    # ---- collection
    def collect(self) -> dict[str, list[Operation]]:
        by_tag: dict[str, list[Operation]] = defaultdict(list)
        name_over = self.overrides.get("names", {})
        group_over = self.overrides.get("groups", {})
        for path, item in self.spec["paths"].items():
            for method, op in item.items():
                if method not in HTTP_METHODS:
                    continue
                key = f"{method.upper()} {path}"
                tag = group_over.get(key) or (op.get("tags") or ["Misc"])[0]
                o = Operation(
                    method=method.upper(),
                    path=path,
                    tag=tag,
                    summary=(op.get("summary") or "").strip(),
                    description=(op.get("description") or "").strip(),
                    op=op,
                )
                o.name = method_name_from_summary(o.summary or f"{method} {path}")
                by_tag[tag].append(o)
        for ops in by_tag.values():
            disambiguate(ops)
            for o in ops:
                key = f"{o.method} {o.path}"
                if key in name_over:
                    o.name = name_over[key]
                if keyword.iskeyword(o.name):
                    o.name += "_"
            names = [o.name for o in ops]
            dupes = {n for n in names if names.count(n) > 1}
            if dupes:
                raise SystemExit(f"duplicate method names in {ops[0].tag}: {sorted(dupes)}")
        return dict(sorted(by_tag.items()))

    # ---- per operation typing
    def resolve(self, o: Operation, ctx: TypeContext) -> None:
        op = o.op
        mp = pascal(o.name)
        taken: set[str] = set()
        params: list[Param] = []
        for p in sorted(op.get("parameters", []), key=lambda p: p["in"] != "path"):
            if p["in"] not in ("path", "query"):
                continue
            schema = p.get("schema", {})
            py = safe_ident(p["name"], taken)
            params.append(
                Param(
                    py=py,
                    wire=p["name"],
                    type=ctx.py_type(schema, f"{mp}{pascal(p['name'])}", for_input=True),
                    required=p["in"] == "path" or bool(p.get("required")),
                    description=(p.get("description") or "").strip(),
                    location=p["in"],
                )
            )
        # path params keep spec order of the template
        order = re.findall(r"{(\w+)}", o.path)
        params.sort(key=lambda p: (p.location != "path", order.index(p.wire) if p.location == "path" else 0))

        rb = op.get("requestBody")
        if rb:
            content = rb.get("content", {})
            o.body_required = bool(rb.get("required"))
            json_s = content.get("application/json", {}).get("schema")
            multi_s = content.get("multipart/form-data", {}).get("schema")
            form_s = content.get("application/x-www-form-urlencoded", {}).get("schema")
            if json_s is not None and multi_s is not None:
                o.body_mode = "json_or_multipart"
                props: dict[str, Any] = {}
                req: set[str] = set()
                for s in (json_s, multi_s):
                    props.update(s.get("properties", {}))
                    req |= set(s.get("required", []))
                req &= set(json_s.get("required", [])) & set(multi_s.get("required", []))
                params += self._body_params(props, req, mp, ctx, taken, multipart=True)
            elif multi_s is not None:
                o.body_mode = "multipart"
                params += self._body_params(
                    multi_s.get("properties", {}),
                    set(multi_s.get("required", [])),
                    mp,
                    ctx,
                    taken,
                    multipart=True,
                )
            elif form_s is not None:
                o.body_mode = "form"
                params += self._body_params(
                    form_s.get("properties", {}),
                    set(form_s.get("required", [])),
                    mp,
                    ctx,
                    taken,
                    multipart=False,
                )
            elif json_s is not None:
                if json_s.get("type") == "object" and json_s.get("properties") and "oneOf" not in json_s:
                    o.body_mode = "json_props"
                    params += self._body_params(
                        json_s["properties"], set(json_s.get("required", [])), mp, ctx, taken, multipart=False
                    )
                else:
                    o.body_mode = "json"
                    params.append(
                        Param(
                            py=safe_ident("body", taken),
                            wire="",
                            type=ctx.py_type(json_s, f"{mp}Body", for_input=True),
                            required=o.body_required,
                            description=(json_s.get("description") or "Request body").strip(),
                            location="rawbody",
                        )
                    )
        o.params = params

        code, resp = pick_success(op)
        if code is None or resp is None:
            o.response_kind = "raw"
            o.return_type = "httpx.Response"
            return
        content = resp.get("content", {})
        if "application/json" in content:
            o.response_kind = "json"
            schema = content["application/json"].get("schema")
            key = f"{o.method} {o.path}"
            forced = self.overrides.get("responses", {}).get(key)
            if forced:
                ctx.used_core.add(forced.removeprefix("list[").removesuffix("]"))
                o.return_type = forced
                return
            if not schema:
                ctx.typing.add("Any")
                o.return_type = "Any"
                return
            target = schema.get("items") if schema.get("type") == "array" else schema
            comp = None
            if isinstance(target, dict) and target.get("type") == "object" and target.get("properties"):
                comp = component_for(target, o.summary, self.comp_props)
            if comp:
                ctx.used_core.add(comp)
                o.return_type = f"list[{comp}]" if schema.get("type") == "array" else comp
            else:
                hint = f"{mp}Item" if schema.get("type") == "array" else f"{mp}Response"
                if schema.get("type") == "array":
                    o.return_type = f"list[{ctx.py_type(schema.get('items'), hint)}]"
                else:
                    o.return_type = ctx.py_type(schema, hint)
        elif content:
            o.response_kind = "binary"
            o.return_type = "bytes"
        else:
            o.response_kind = "none"
            o.return_type = "None"

    def _body_params(
        self,
        props: dict[str, Any],
        required: set[str],
        mp: str,
        ctx: TypeContext,
        taken: set[str],
        *,
        multipart: bool,
    ) -> list[Param]:
        out: list[Param] = []
        for name, ps in props.items():
            is_file = ps.get("format") == "binary" or (
                ps.get("type") == "array" and (ps.get("items") or {}).get("format") == "binary"
            )
            py = safe_ident(name, taken)
            out.append(
                Param(
                    py=py,
                    wire=name,
                    type=ctx.py_type(ps, f"{mp}{pascal(name)}", for_input=True),
                    required=name in required,
                    description=(ps.get("description") or "").strip(),
                    location="file" if (is_file and multipart) else "body",
                )
            )
        return out

    # ---- rendering
    def render_method(self, o: Operation, *, is_async: bool) -> list[str]:
        L: list[str] = []
        pos = [p for p in o.params if p.location == "path"]
        kw = [p for p in o.params if p.location != "path"]
        kw.sort(key=lambda p: not p.required)
        sig = ["self"]
        for p in pos:
            sig.append(f"{p.py}: {p.type}")
        rest: list[str] = []
        for p in kw:
            if p.required:
                rest.append(f"{p.py}: {p.type}")
            else:
                t = p.type if p.type == "Any" or p.type.endswith("| None") else f"{p.type} | None"
                rest.append(f"{p.py}: {t} = None")
        if o.body_mode in ("json_props", "json_or_multipart", "multipart", "form"):
            rest.append("extra_body: Mapping[str, Any] | None = None")
        d = "async def" if is_async else "def"

        def emit(params: list[str], ret: str, *, stub: bool = False) -> None:
            full = [py39_param(x) for x in sig + (["*", *params] if params else [])]
            ret = py39_type(ret)
            end = " ..." if stub else ""
            one_line = f"    {d} {o.name}({', '.join(full)}) -> {ret}:{end}"
            if len(one_line) <= 88:
                L.append(one_line)
            else:
                L.append(f"    {d} {o.name}(")
                for s in full:
                    L.append(f"        {s},")
                L.append(f"    ) -> {ret}:{end}")

        if o.response_kind == "binary":
            # Overloads: no dest → bytes, a dest → the written Path.
            L.append("    @overload")
            emit([*rest, "dest: None = None"], "bytes", stub=True)
            L.append("")
            L.append("    @overload")
            emit([*rest, "dest: str | os.PathLike[str]"], "Path", stub=True)
            L.append("")
            emit([*rest, "dest: str | os.PathLike[str] | None = None"], "bytes | Path")
        else:
            emit(rest, o.return_type)
        # docstring
        L.append('        """' + doc_escape(o.summary or o.name).rstrip(".") + ".")
        if o.description and o.description != o.summary:
            L.append("")
            L.extend(wrap(o.description, "        "))
        documented = [p for p in o.params if p.description]
        if documented or o.response_kind == "binary":
            L.append("")
            L.append("        Args:")
            for p in documented:
                lines = wrap(f"{p.py}: {p.description}", "            ")
                L.append(lines[0])
                L.extend("    " + x if x else x for x in lines[1:])
            if o.response_kind == "binary":
                L.append("            dest: Write the content to this file and return its path.")
        L.append("")
        L.append(f"        ``{o.method} {o.path}``")
        L.append('        """')
        # body
        call: list[str] = [repr(o.method), repr(o.path)]
        if pos:
            call.append("path_params={" + ", ".join(f"{p.wire!r}: {p.py}" for p in pos) + "}")
        q = [p for p in o.params if p.location == "query"]
        if q:
            call.append("params={" + ", ".join(f"{p.wire!r}: {p.py}" for p in q) + "}")
        body = [p for p in o.params if p.location == "body"]
        files = [p for p in o.params if p.location == "file"]
        if o.body_mode == "json":
            raw = next(p for p in o.params if p.location == "rawbody")
            call.append(f"json={raw.py}")
        elif o.body_mode in ("json_props", "json_or_multipart", "multipart", "form"):
            call.append("body={" + ", ".join(f"{p.wire!r}: {p.py}" for p in body) + "}")
            call.append("extra_body=extra_body")
            if files:
                call.append("files={" + ", ".join(f"{p.wire!r}: {p.py}" for p in files) + "}")
            call.append(f"body_mode={o.body_mode!r}")
        if o.response_kind == "json":
            call.append(
                f"response_type={py39_type(o.return_type)}" if o.return_type != "Any" else "response_type=None"
            )
        elif o.response_kind == "binary":
            call.append("binary=True")
            call.append("dest=dest")
        elif o.response_kind == "raw":
            call.append("raw=True")
        aw = "await " if is_async else ""
        stmt = f"        return {aw}self._t.request({', '.join(call)})"
        if len(stmt) <= 88:
            L.append(stmt)
        else:
            L.append(f"        return {aw}self._t.request(")
            for c in call:
                L.append(f"            {c},")
            L.append("        )")
        return L

    def render_group(self, tag: str, ops: list[Operation], ctx: TypeContext) -> str:
        cls = pascal(tag) + "Group"
        mod = group_name(tag)
        sync_methods: list[str] = []
        async_methods: list[str] = []
        for o in ops:
            sync_methods += ["", *self.render_method(o, is_async=False)]
            async_methods += ["", *self.render_method(o, is_async=True)]
        body = "\n".join(sync_methods + async_methods)
        local_models = sorted(n for n in (*ctx.models, *ctx.aliases) if re.search(rf"\b{n}\b", body))
        core = sorted(n for n in ctx.used_core if re.search(rf"\b{n}\b", body))

        head = [
            GENERATED_HEADER.rstrip(),
            f'"""Operations of the *{tag}* group."""',
            "",
            "from __future__ import annotations",
            "",
        ]
        std: list[str] = []
        if "os.PathLike" in body:
            std.append("import os")
        if "_dt." in body:
            std.append("import datetime as _dt")
        if "Path" in body:
            std.append("from pathlib import Path")
        typing_names = ["TYPE_CHECKING"]
        for n in ("Any", "Literal", "Optional", "Union", "overload"):
            if re.search(rf"\b{n}\b", body):
                typing_names.append(n)
        std.append(f"from typing import {', '.join(sorted(typing_names))}")
        if "Mapping[" in body:
            std.append("from collections.abc import Mapping")
        head += sorted(std, key=lambda s: (s.startswith("from"), s))
        head.append("")
        if "httpx.Response" in body:
            head.append("import httpx")
            head.append("")
        if "FileInput" in body:
            head.append("from .._transport import FileInput")
        if core:
            head.append(f"from ..models._core import {', '.join(core)}")
        if local_models:
            head.append(f"from ._models.{mod} import {', '.join(local_models)}")
        head += [
            "",
            "if TYPE_CHECKING:",
            "    from .._transport import AsyncTransport, SyncTransport",
            "",
            "",
            f"class {cls}:",
            f'    """Synchronous operations of the *{tag}* group."""',
            "",
            "    def __init__(self, transport: SyncTransport) -> None:",
            "        self._t = transport",
        ]
        mid = [
            "",
            "",
            f"class Async{cls}:",
            f'    """Asynchronous operations of the *{tag}* group."""',
            "",
            "    def __init__(self, transport: AsyncTransport) -> None:",
            "        self._t = transport",
        ]
        return "\n".join(head + sync_methods + mid + async_methods) + "\n"

    def render_group_models(self, tag: str, ctx: TypeContext) -> str:
        models = list(ctx.models.values())
        text = "\n".join(render_models(models))
        lines = [
            GENERATED_HEADER.rstrip(),
            f'"""Inline models of the *{tag}* group."""',
            "",
            "from __future__ import annotations",
            "",
        ]
        if "_dt." in text:
            lines.append("import datetime as _dt")
        tn = [n for n in ("Any", "Literal", "Optional", "Union") if re.search(rf"\b{n}\b", text)]
        if tn:
            lines.append(f"from typing import {', '.join(tn)}")
        lines.append("")
        imports = ["KitsuModel"]
        if "Field(" in text:
            lines.append("from pydantic import Field")
            lines.append("")
        if "FileInput" in text:
            lines.append("from .._transport import FileInput  # noqa: F401")
        lines.append(f"from ...models._base import {', '.join(imports)}")
        core = sorted(n for n in ctx.used_core if re.search(rf"\b{n}\b", text))
        if core:
            lines.append(f"from ...models._core import {', '.join(core)}")
        lines.append("")
        lines.append(f"__all__ = {sorted([*ctx.models, *ctx.aliases])!r}")
        lines += text.splitlines()
        lines.append("")
        if ctx.aliases:
            lines.append("")
            lines.append("# Routes answering with the same shape share one class.")
            for alias, target in ctx.aliases.items():
                lines.append(f"{alias} = {target}")
            lines.append("")
        # Resolve forward references between models declared in any order.
        for m in models:
            lines.append(f"{m.name}.model_rebuild()")
        return "\n".join(lines) + "\n"

    def render_core(self) -> tuple[str, list[str]]:
        ctx = TypeContext(self.components, set(), "core")
        for name in sorted(self.components):
            ctx.models[name] = ModelDef(name=name, fields=[])
        for name, s in sorted(self.components.items()):
            extra = {k: v for k, v in BASE_FIELDS.items() if k not in s.get("properties", {})}
            m = ctx.build_model(name, s, for_input=False, extra_props=extra)
            ctx.models[name] = m
        models = list(ctx.models.values())
        text = "\n".join(render_models(models))
        lines = [
            GENERATED_HEADER.rstrip(),
            '"""Component models of the Kitsu API (database rows)."""',
            "",
            "from __future__ import annotations",
            "",
        ]
        if "_dt." in text:
            lines.append("import datetime as _dt")
        tn = [n for n in ("Any", "Literal", "Optional", "Union") if re.search(rf"\b{n}\b", text)]
        if tn:
            lines.append(f"from typing import {', '.join(tn)}")
        lines.append("")
        if "Field(" in text:
            lines.append("from pydantic import Field")
            lines.append("")
        lines.append("from ._base import KitsuModel")
        lines.append("")
        lines.append(f"__all__ = {sorted(ctx.models)!r}")
        lines += text.splitlines()
        lines.append("")
        for m in models:
            lines.append(f"{m.name}.model_rebuild()")
        return "\n".join(lines) + "\n", sorted(ctx.models)

    def render_models_init(self, core_names: list[str]) -> str:
        lines = [
            GENERATED_HEADER.rstrip(),
            '"""Kitsu models, imported lazily.',
            "",
            "``from pykitsu.models import Shot`` only imports pydantic and the component",
            "models at that moment, not when ``pykitsu`` is imported.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "import importlib",
            "from typing import TYPE_CHECKING, Any",
            "",
            "if TYPE_CHECKING:",
            "    from ._base import KitsuModel",
        ]
        for n in core_names:
            lines.append(f"    from ._core import {n}")
        lines += [
            "",
            "_LAZY: dict[str, str] = {",
            '    "KitsuModel": "._base",',
        ]
        for n in core_names:
            lines.append(f"    {n!r}: '._core',")
        lines += [
            "}",
            "",
            f"__all__ = {['KitsuModel', *core_names]!r}",
            "",
            "",
            "def __getattr__(name: str) -> Any:",
            "    module = _LAZY.get(name)",
            "    if module is None:",
            '        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")',
            "    value = getattr(importlib.import_module(module, __name__), name)",
            "    globals()[name] = value",
            "    return value",
            "",
            "",
            "def __dir__() -> list[str]:",
            "    return sorted(__all__)",
        ]
        return "\n".join(lines) + "\n"

    def render_groups_mixin(self, tags: list[str]) -> str:
        lines = [
            GENERATED_HEADER.rstrip(),
            '"""Lazy group properties of the clients.',
            "",
            "Each property imports its group module the first time it is used, so",
            "building a client stays cheap however many groups the API has.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "from typing import TYPE_CHECKING, Any",
            "",
            "if TYPE_CHECKING:",
            "    from ._transport import AsyncTransport, SyncTransport",
        ]
        for t in tags:
            lines.append(f"    from .groups.{group_name(t)} import Async{pascal(t)}Group, {pascal(t)}Group")
        lines += [
            "",
            f"GROUP_NAMES: tuple[str, ...] = {tuple(group_name(t) for t in tags)!r}",
        ]
        for is_async in (False, True):
            prefix = "Async" if is_async else ""
            tr = "AsyncTransport" if is_async else "SyncTransport"
            lines += [
                "",
                "",
                f"class _{prefix}Groups:",
                "    _transport: " + tr,
                "    _groups: dict[str, Any]",
            ]
            for t in tags:
                sn, cls = group_name(t), f"{prefix}{pascal(t)}Group"
                lines += [
                    "",
                    "    @property",
                    f"    def {sn}(self) -> {cls}:",
                    f'        """Operations of the *{t}* group (imported on first use)."""',
                    f"        group = self._groups.get({sn!r})",
                    "        if group is None:",
                    f"            from .groups.{sn} import {cls}",
                    "",
                    f"            group = self._groups[{sn!r}] = {cls}(self._transport)",
                    "        return group",
                ]
        return "\n".join(lines) + "\n"

    # ---- orchestration
    def run(self) -> None:
        by_tag = self.collect()
        core_src, core_names = self.render_core()
        core_set = set(core_names)

        groups_dir = PKG / "groups"
        models_dir = groups_dir / "_models"
        for d in (groups_dir, models_dir):
            d.mkdir(parents=True, exist_ok=True)
            for f in d.glob("*.py"):
                f.unlink()
        (PKG / "models").mkdir(exist_ok=True)
        (PKG / "models" / "_core.py").write_text(core_src)
        (PKG / "models" / "__init__.py").write_text(self.render_models_init(core_names))
        (groups_dir / "__init__.py").write_text(
            GENERATED_HEADER + '"""Generated API groups. Import them through the client properties."""\n'
        )
        (models_dir / "__init__.py").write_text(GENERATED_HEADER)

        stats = []
        for tag, ops in by_tag.items():
            ctx = TypeContext(self.components, core_set, group_name(tag))
            for o in ops:
                self.resolve(o, ctx)
            (groups_dir / f"{group_name(tag)}.py").write_text(self.render_group(tag, ops, ctx))
            (models_dir / f"{group_name(tag)}.py").write_text(self.render_group_models(tag, ctx))
            stats.append((tag, len(ops), len(ctx.models)))
        (PKG / "_groups.py").write_text(self.render_groups_mixin(list(by_tag)))
        (PKG / "_spec_version.py").write_text(
            GENERATED_HEADER + f"SPEC_VERSION = {self.spec['info'].get('version', '')!r}\n"
        )

        for tag, n_ops, n_models in stats:
            print(f"  {group_name(tag):<20} {n_ops:>4} operations {n_models:>4} models")
        print(f"  total: {sum(s[1] for s in stats)} operations, {len(core_names)} core models")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    ap.add_argument("--fetch", nargs="?", const=SPEC_URL, help="download the spec first (default: %(const)s)")
    ap.add_argument("--no-format", action="store_true", help="skip ruff format/fix")
    args = ap.parse_args()

    if args.fetch:
        print(f"fetching {args.fetch}")
        with urllib.request.urlopen(args.fetch) as r:
            data = json.load(r)
        args.spec.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")

    spec = json.loads(args.spec.read_text())
    overrides = tomllib.loads(OVERRIDES.read_text()) if OVERRIDES.exists() else {}
    Generator(spec, overrides).run()

    if not args.no_format:
        targets = [str(PKG / "groups"), str(PKG / "models"), str(PKG / "_groups.py")]
        for cmd in (
            ["ruff", "check", "--fix-only", "--quiet", *targets],
            ["ruff", "format", "--quiet", *targets],
        ):
            try:
                subprocess.run([sys.executable, "-m", *cmd], check=True)
            except (subprocess.CalledProcessError, FileNotFoundError) as exc:
                print(f"warning: {' '.join(cmd)} failed: {exc}", file=sys.stderr)


if __name__ == "__main__":
    main()
